import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const target = path.join(root, 'supabase/functions/_shared/knowledge');
await mkdir(target, { recursive: true });
for (const name of ['data.ts', 'clarify-flow.ts', 'fbo-knowledge.ts']) {
  const source = await readFile(path.join(root, 'src/lib', name), 'utf8');
  const output = '// Generated by scripts/sync-edge-knowledge.mjs; edit src/lib instead.\n' +
    source.replace('from "./data"', 'from "./data.ts"');
  const dest = path.join(target, name);
  if (process.argv.includes('--check')) {
    if (await readFile(dest, 'utf8') !== output) throw new Error(`Stale Edge knowledge: ${name}`);
  } else await writeFile(dest, output);
}
const manual = await readFile(path.join(root, 'src/lib/survey-manual.txt'), 'utf8');
const output = '// Generated; edit src/lib/survey-manual.txt instead.\nexport default ' + JSON.stringify(manual) + ';\n';
if (process.argv.includes('--check')) {
  if (await readFile(path.join(target, 'survey-manual.ts'), 'utf8') !== output) throw new Error('Stale survey manual');
} else await writeFile(path.join(target, 'survey-manual.ts'), output);
